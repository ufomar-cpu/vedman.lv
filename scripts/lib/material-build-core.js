export function buildSitemapXml(urls) {
  const normalized = urls.map((loc) => {
    let full = loc;
    if (!full.startsWith("http")) full = SITE_ORIGIN + (loc.startsWith("/") ? loc : "/" + loc);
    if (full === SITE_ORIGIN) return SITE_ORIGIN + "/";
    if (full.includes(".html")) return full;
    return full.endsWith("/") ? full : full + "/";
  });
  const unique = [...new Set(normalized)];
  const body = unique.map((loc) => "<url><loc>" + escapeXml(loc) + "</loc></url>").join("");
  return '<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' + body + "</urlset>";
}

export function discoverHandMaintainedSlugs(materialiDir) {
  const slugs = [];
  if (!existsSync(materialiDir)) return slugs;
  for (const name of readdirSync(materialiDir)) {
    if (name.startsWith("_")) continue;
    const indexPath = join(materialiDir, name, "index.html");
    if (!existsSync(indexPath)) continue;
    const content = readFileSync(indexPath, "utf8");
    if (!isGeneratedFile(content)) slugs.push(name);
  }
  return slugs;
}

export function listGeneratedSlugs(materialiDir) {
  const slugs = [];
  if (!existsSync(materialiDir)) return slugs;
  for (const name of readdirSync(materialiDir)) {
    const indexPath = join(materialiDir, name, "index.html");
    if (!existsSync(indexPath)) continue;
    const content = readFileSync(indexPath, "utf8");
    if (isGeneratedFile(content)) slugs.push(name);
  }
  return slugs;
}

export function sha256(content) {
  return createHash("sha256").update(content).digest("hex");
}

export function generateMaterialPages({ repoRoot, dataDir }) {
  const materialiDir = join(repoRoot, "materiali");
  const manifest = readBuildManifest(dataDir);
  const materials = loadPublishedMaterials(dataDir, manifest);
  const expectedSlugs = new Set(materials.map((m) => m.slug));
  const results = { generated: [], removed: [], sitemapUrls: [] };

  for (const { payload, slug } of materials) {
    const dir = resolveMaterialOutputDir(materialiDir, slug);
    const indexPath = join(dir, "index.html");
    if (existsSync(indexPath)) {
      const existing = readFileSync(indexPath, "utf8");
      if (!isGeneratedFile(existing)) {
        throw new Error("Roku uzturēta lapa — ģenerēšana apstādināta: materiali/" + slug + "/index.html");
      }
    }
    mkdirSync(dir, { recursive: true });
    const html = renderMaterialPage(payload);
    writeFileSync(indexPath, html, "utf8");
    results.generated.push({ slug, path: indexPath, hash: sha256(html) });
    results.sitemapUrls.push(publicMaterialUrl(slug));
  }

  for (const slug of listGeneratedSlugs(materialiDir)) {
    if (!expectedSlugs.has(slug)) {
      const dir = resolveMaterialOutputDir(materialiDir, slug);
      rmSync(dir, { recursive: true, force: true });
      results.removed.push(slug);
    }
  }

  const handSlugs = discoverHandMaintainedSlugs(materialiDir);
  for (const slug of handSlugs) {
    if (isValidSlug(slug)) results.sitemapUrls.push(publicMaterialUrl(slug));
  }

  const allUrls = [
    ...STATIC_SITEMAP_PATHS.map((p) => (p === "/" ? SITE_ORIGIN + "/" : SITE_ORIGIN + p)),
    ...results.sitemapUrls
  ];
  const sitemapXml = buildSitemapXml(allUrls);
  writeFileSync(join(repoRoot, "sitemap.xml"), sitemapXml, "utf8");
  results.sitemapPath = join(repoRoot, "sitemap.xml");
  results.manifest = manifest;
  return results;
}

export function validateGeneratedRoutes({ repoRoot, dataDir }) {
  const materialiDir = join(repoRoot, "materiali");
  const manifest = readBuildManifest(dataDir);
  const materials = loadPublishedMaterials(dataDir, manifest);
  const errors = [];
  const canonicals = new Set();

  for (const { payload, slug } of materials) {
    const indexPath = join(materialiDir, slug, "index.html");
    const canonical = publicMaterialUrl(slug);
    if (!existsSync(indexPath)) {
      errors.push(slug + ": trūkst index.html");
      continue;
    }
    const html = readFileSync(indexPath, "utf8");
    if (!isGeneratedFile(html)) {
      errors.push(slug + ": nav ģenerēts fails");
      continue;
    }
    if (!html.includes('rel="canonical" href="' + canonical + '"')) {
      errors.push(slug + ": nepareizs canonical");
    }
    if (!html.includes('id="passport-title">' + escapeHtml(payload.title) + "</h1>")) {
      errors.push(slug + ": trūkst vai nepareizs h1 virsraksts");
    }
    if (FORBIDDEN_PUBLIC.test(html)) errors.push(slug + ": satur aizliegtu tekstu");
    if (canonicals.has(canonical)) errors.push(slug + ": dublēts canonical");
    canonicals.add(canonical);
  }

  const sitemapPath = join(repoRoot, "sitemap.xml");
  if (!existsSync(sitemapPath)) errors.push("Trūkst sitemap.xml");
  else {
    const xml = readFileSync(sitemapPath, "utf8");
    for (const { slug } of materials) {
      const url = publicMaterialUrl(slug);
      if (!xml.includes(escapeXml(url))) errors.push(slug + ": nav sitemap.xml");
    }
    for (const slug of listGeneratedSlugs(materialiDir)) {
      if (!materials.some((m) => m.slug === slug)) {
        errors.push("Obsolete generated folder: " + slug);
      }
    }
  }

  return { ok: errors.length === 0, errors, count: materials.length };
}
