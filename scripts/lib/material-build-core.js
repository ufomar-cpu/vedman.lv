/**
 * Node build utilities for VEDMAN material passport pages.
 * Build input: data/published-materials/ (manifest + sanitized JSON per slug).
 * CI may populate via scripts/sync-published-data.js (anonymous Firebase Storage read).
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync } from "node:fs";
import { join, dirname, resolve, relative } from "node:path";
import { createHash } from "node:crypto";

export const GENERATED_MARKER = "<!-- GENERATED BY VEDMAN MATERIAL BUILD — DO NOT EDIT -->";
export const SITE_ORIGIN = "https://vedman.lv";
export const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
export const FORBIDDEN_PUBLIC = /\[TBD\]|lorem ipsum|TODO|FIXME|margin|supplier price/i;
export const PRIVATE_KEYS = new Set([
  "revision", "lastPublishedSlug", "_draft", "_status", "publishError",
  "publicationState", "publicVerifiedAt", "publicUrl", "publishedRevision"
]);

export const STATIC_SITEMAP_PATHS = [
  "/",
  "/privacy.html"
];

export function escapeHtml(str) {
  return String(str ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

export function escapeXml(str) {
  return String(str ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

export function publicMaterialUrl(slug) {
  return SITE_ORIGIN + "/materiali/" + slug + "/";
}

export function isValidSlug(slug) {
  if (typeof slug !== "string") return false;
  if (slug.length === 0 || slug.length > 80) return false;
  if (slug.includes(".") || slug.includes("/") || slug.includes("\\")) return false;
  if (slug.includes("..") || /%2e|%2f|%5c/i.test(slug)) return false;
  return SLUG_RE.test(slug);
}

export function resolveMaterialOutputDir(materialiDir, slug) {
  if (!isValidSlug(slug)) throw new Error("Nederīgs slug: " + slug);
  const dir = resolve(materialiDir, slug);
  const base = resolve(materialiDir);
  const rel = relative(base, dir);
  if (rel.startsWith("..") || rel.includes("..")) {
    throw new Error("Slug path traversal blocked: " + slug);
  }
  return dir;
}

export function serializePassportJson(payload) {
  return JSON.stringify(payload)
    .replace(/</g, "\\u003c")
    .replace(/>/g, "\\u003e")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}

export function isGeneratedFile(content) {
  return String(content).includes(GENERATED_MARKER);
}

export function scanForbidden(obj, depth = 0) {
  const hits = [];
  if (!obj || typeof obj !== "object" || depth > 8) return hits;
  for (const [k, v] of Object.entries(obj)) {
    if (PRIVATE_KEYS.has(k)) hits.push(k);
    if (typeof v === "string" && FORBIDDEN_PUBLIC.test(v)) hits.push(k);
    else if (v && typeof v === "object") hits.push(...scanForbidden(v, depth + 1));
  }
  return hits;
}

export function validatePublishedMaterial(payload, expectedSlug = null) {
  const errors = [];
  if (!payload || typeof payload !== "object") errors.push("Trūkst publicējamā satura");
  if (!payload?.title) errors.push("Trūkst nosaukuma");
  if (!payload?.urlSlug || !isValidSlug(payload.urlSlug)) errors.push("Nederīgs slug");
  if (expectedSlug && payload?.urlSlug !== expectedSlug) errors.push("Slug neatbilst faila nosaukumam");
  const heroRole = payload?.content?.heroRole || "hero";
  const hero = payload?.images?.[heroRole];
  if (!hero?.url && !hero?.available) errors.push("Trūkst hero attēla");
  const forbidden = scanForbidden(payload);
  if (forbidden.length) errors.push("Aizliegts vai privāts saturs: " + forbidden.join(", "));
  return errors;
}

export function readBuildManifest(dataDir) {
  const path = join(dataDir, "manifest.json");
  if (!existsSync(path)) throw new Error("Trūkst manifest.json: " + path);
  const manifest = JSON.parse(readFileSync(path, "utf8"));
  if (!manifest || !Array.isArray(manifest.materials)) {
    throw new Error("Nederīgs manifest.json — gaidīts materials[] masīvs");
  }
  return manifest;
}

export function loadPublishedMaterials(dataDir, manifest) {
  const materials = [];
  const seen = new Set();
  for (const entry of manifest.materials) {
    const slug = entry.urlSlug;
    if (!isValidSlug(slug)) throw new Error("Nederīgs manifest slug: " + slug);
    if (seen.has(slug)) throw new Error("Dublēts slug manifestā: " + slug);
    seen.add(slug);
    const filePath = join(dataDir, "materials", slug + ".json");
    if (!existsSync(filePath)) throw new Error("Trūkst materiāla JSON: " + filePath);
    let payload;
    try {
      payload = JSON.parse(readFileSync(filePath, "utf8"));
    } catch (e) {
      throw new Error("Bojāts JSON " + filePath + ": " + e.message);
    }
    const errors = validatePublishedMaterial(payload, slug);
    if (errors.length) throw new Error(slug + ": " + errors.join("; "));
    materials.push({ entry, payload, slug });
  }
  return materials;
}

export function buildStructuredData(payload, canonical) {
  const faq = (payload.content?.faq || []).slice(0, 8).map((f) => ({
    "@type": "Question",
    name: f.question,
    acceptedAnswer: { "@type": "Answer", text: f.answer }
  }));
  const graph = [
    {
      "@type": "BreadcrumbList",
      itemListElement: [
        { "@type": "ListItem", position: 1, name: "VEDMAN", item: SITE_ORIGIN + "/" },
        { "@type": "ListItem", position: 2, name: "Materiāli", item: SITE_ORIGIN + "/#materiali" },
        { "@type": "ListItem", position: 3, name: payload.title, item: canonical }
      ]
    },
    {
      "@type": "Product",
      name: payload.title,
      description: payload.content?.description || payload.content?.seo?.metaDescription || "",
      brand: { "@type": "Brand", name: "VEDMAN" },
      category: payload.content?.materialType || "Beramie materiāli",
      url: canonical,
      image: payload.images?.[payload.content?.heroRole || "hero"]?.url || SITE_ORIGIN + "/assets/logos/vedman-logo.png"
    }
  ];
  if (faq.length) graph.push({ "@type": "FAQPage", mainEntity: faq });
  return JSON.stringify({ "@context": "https://schema.org", "@graph": graph }, null, 0);
}

